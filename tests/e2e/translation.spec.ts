import { expect, test } from '@playwright/test'
import { cp } from 'node:fs/promises'
import { join } from 'node:path'
import { chapterQuotes, closeAllApps, configureLlm, enableSelectionStore, importFixture,
  launch, slowDragSelectInChapter, waitForLocationsReady } from './helpers'
import { closeFakeTranslations, startFakeTranslation } from './fake-translation'
import { closeAllFakeLlms, startFakeLlm } from './fake-llm'

test.afterEach(async () => { await closeAllApps(); await closeFakeTranslations(); await closeAllFakeLlms() })

test('未配置聊天 API 也能翻译；首次授权、仅发送选文、重启持久化并进入聊天上下文', async () => {
  const translator = await startFakeTranslation()
  let h = await launch(undefined, { READER_TRANSLATION_TEST_URL: translator.url })
  await enableSelectionStore(h)
  await importFixture(h)
  await h.page.getByTestId('book-card').first().click()
  await waitForLocationsReady(h)
  await slowDragSelectInChapter(h)
  const quote = (await chapterQuotes(h))[0]
  const before = await h.page.getByTestId('page-indicator').textContent()
  await h.page.getByTestId('quote-chip').hover()
  await h.page.getByTestId('quote-translate').click()
  await expect(h.page.getByTestId('translation-consent')).toBeVisible()
  await h.page.getByTestId('translation-consent').getByRole('button', { name: '取消', exact: true }).click()
  expect(translator.texts).toHaveLength(0)
  await h.page.getByTestId('quote-chip').hover()
  await h.page.getByTestId('quote-translate').click()
  await h.page.getByTestId('translation-consent-yes').click()
  await expect(h.page.getByTestId('message-assistant')).toContainText('〔在线翻译〕')
  await expect(h.page.getByTestId('message-assistant')).toContainText('这是独立翻译结果。')
  expect(translator.texts.join('')).toBe(quote.text)
  await expect(h.page.getByTestId('page-indicator')).toHaveText(before!)
  const userData = h.userData
  await h.app.close()
  h = await launch(userData, { READER_TRANSLATION_TEST_URL: translator.url })
  await h.page.getByTestId('book-card').first().click()
  await waitForLocationsReady(h)
  await expect(h.page.getByTestId('message-assistant')).toContainText('这是独立翻译结果。')
  const llm = await startFakeLlm()
  await configureLlm(h, { endpoint: llm.url })
  await h.page.getByTestId('book-card').first().click()
  await waitForLocationsReady(h)
  await h.page.getByTestId('chat-input').fill('解释译文')
  await h.page.getByTestId('chat-send').click()
  await expect(h.page.getByTestId('message-assistant').last()).toContainText('这是假的回答。')
  expect(llm.requests[0].body.messages?.map((message) => message.content).join('\n')).toContain('这是独立翻译结果。')
})

test('离线设置独立保存，未安装时明确提示且不会转在线；免费额度耗尽可重试', async () => {
  const translator = await startFakeTranslation()
  const h = await launch(undefined, { READER_TRANSLATION_TEST_URL: translator.url })
  await h.page.getByTestId('open-settings').click()
  await expect(h.page.getByTestId('translation-pack')).toContainText('未安装')
  await h.page.getByTestId('translation-mode').selectOption('offline')
  await expect.poll(() => h.page.evaluate(() => window.api.getSetting('translation.mode'))).toBe('offline')
  await h.page.getByRole('button', { name: '← 返回书架' }).click()
  await enableSelectionStore(h)
  await importFixture(h)
  await h.page.getByTestId('book-card').first().click()
  await waitForLocationsReady(h)
  await slowDragSelectInChapter(h)
  await h.page.getByTestId('quote-chip').hover()
  await h.page.getByTestId('quote-translate').click()
  await expect(h.page.getByTestId('chat-error')).toContainText('下载')
  expect(translator.texts).toHaveLength(0)
  await h.page.getByRole('button', { name: '← 书架' }).click()
  await h.page.getByTestId('open-settings').click()
  await h.page.getByTestId('translation-mode').selectOption('online')
  await h.page.getByTestId('translation-online-consent').check()
  await expect.poll(() => h.page.evaluate(() => window.api.getSetting('translation.onlineConsent'))).toBe('true')
  await h.page.getByRole('button', { name: '← 返回书架' }).click()
  await h.page.getByTestId('book-card').first().click()
  await waitForLocationsReady(h)
  translator.setMode('quota')
  await slowDragSelectInChapter(h)
  await h.page.getByTestId('quote-chip').hover()
  await h.page.getByTestId('quote-translate').click()
  await expect(h.page.getByTestId('chat-error')).toContainText('额度')
  translator.setMode('ok')
  await h.page.getByTestId('chat-retry').click()
  await expect(h.page.getByTestId('message-assistant').last()).toContainText('这是独立翻译结果。')
})

test('真实离线模型在 Electron 工作线程中翻译，重启安装态恢复，不访问在线接口', async () => {
  test.skip(!process.env.READER_OFFLINE_SMOKE_PATH, '显式模型烟测；普通测试不下载真实模型')
  const translator = await startFakeTranslation()
  let h = await launch(undefined, { READER_TRANSLATION_TEST_URL: translator.url })
  await cp(process.env.READER_OFFLINE_SMOKE_PATH!, join(h.userData, 'translation'), { recursive: true })
  const userData = h.userData
  await h.app.close()
  h = await launch(userData, { READER_TRANSLATION_TEST_URL: translator.url })
  await h.page.getByTestId('open-settings').click()
  await expect(h.page.getByTestId('translation-pack')).toContainText('已安装')
  await h.page.getByTestId('translation-mode').selectOption('offline')
  await expect.poll(() => h.page.evaluate(() => window.api.getSetting('translation.mode'))).toBe('offline')
  await h.page.getByRole('button', { name: '← 返回书架' }).click()
  await enableSelectionStore(h)
  await importFixture(h)
  await h.page.getByTestId('book-card').first().click()
  await waitForLocationsReady(h)
  await slowDragSelectInChapter(h)
  await h.page.getByTestId('quote-chip').hover()
  await h.page.getByTestId('quote-translate').click()
  await expect(h.page.getByTestId('message-assistant')).toContainText('〔离线翻译〕', { timeout: 60000 })
  expect(translator.texts).toHaveLength(0)
  await h.page.getByRole('button', { name: '← 书架' }).click()
  await h.page.getByTestId('open-settings').click()
  await h.page.getByTestId('translation-pack-remove').click()
  await h.page.getByTestId('translation-remove-yes').click()
  await expect(h.page.getByTestId('translation-pack')).toContainText('未安装')
})
